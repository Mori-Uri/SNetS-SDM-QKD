package qkd.verification;

import java.util.ArrayList;
import java.util.List;
import qkd.multiband.ClassicalPowerEvolution;
import network.LongitudinalClassicalQoT;

/** Scientific limiting-case and integrated physical-chain checks (Java 8). */
public final class QKDBoosterIntegratedVerification {
	private static final double H=6.62607015e-34;
	private static final double F=193.4e12;
	private static final double ALPHA=0.2;
	private static final double EPS=1e-10;
	private QKDBoosterIntegratedVerification() { }
	private static void ok(boolean value, String label) {
		if (!value) throw new AssertionError(label);
	}

	private static void near(double expected,double actual,double relative,String label) {
		ok(Double.isFinite(actual) && Math.abs(actual-expected)
				<= relative*Math.max(Math.abs(expected),EPS),label
				+ ": expected="+expected+" actual="+actual);
	}

	private static ClassicalPowerEvolution template(boolean saturated,double gain) {
		return new ClassicalPowerEvolution(80,16,
				saturated ? ClassicalPowerEvolution.GainModel.SATURATED
						  : ClassicalPowerEvolution.GainModel.IDEAL,
				16,0,5,100).withBooster(gain,0.04,saturated);
	}

	private static List<ClassicalPowerEvolution.LoadSource> loads(boolean downstreamPiCh) {
		List<ClassicalPowerEvolution.LoadSource> src =
				new ArrayList<ClassicalPowerEvolution.LoadSource>();
		src.add(new ClassicalPowerEvolution.LoadSource(.01,0,240,F,32e9));

		if(downstreamPiCh) src.add(new ClassicalPowerEvolution.LoadSource(.1,100,200,F+100e9,32e9));

		return src;
	}

	public static void main(String[] args) {
		ClassicalPowerEvolution ideal=template(false,10).withDynamicLoad(loads(false),240,ALPHA);
		ClassicalPowerEvolution saturated=template(true,10).withDynamicLoad(loads(false),240,ALPHA);
		ClassicalPowerEvolution noBooster=template(true,1).withDynamicLoad(loads(false),240,ALPHA);
		near(10,ideal.getBoosterGainLinear(),1e-12,"ideal booster fixed");
		ok(saturated.getBoosterGainLinear()<10,"booster compresses under load");
		near(.01,saturated.getBoosterInputPowerW(),1e-12,"booster sees launched load");
		ok(saturated.inputPowerWAt(1)>noBooster.inputPowerWAt(1),
				"booster signal must reach line-EDFA input");
		ok(saturated.gainLinearAt(1,ALPHA)<noBooster.gainLinearAt(1,ALPHA),
				"booster increases line compression");
		near(ideal.getBoosterGainLinear()*Math.exp(-ALPHA*40),
				ideal.powerRatio(0,40,ALPHA),1e-12,"passive first-span closed-form");

		// Sources created downstream of the input booster must not inherit its gain.
		ClassicalPowerEvolution withPich=template(true,10).withDynamicLoad(loads(true),240,ALPHA);
		near(saturated.getBoosterGainLinear(),withPich.getBoosterGainLinear(),1e-12,
				"downstream PICh cannot saturate input booster");
		near(saturated.inputPowerWAt(1),withPich.inputPowerWAt(1),1e-12,
				"PICh after first EDFA cannot affect its input");
		ok(withPich.inputPowerWAt(2)>saturated.inputPowerWAt(2),
				"PICh between line EDFAs must contribute to downstream load");
		ok(withPich.gainLinearAt(2,ALPHA)<saturated.gainLinearAt(2,ALPHA),
				"downstream line EDFA must compress with PICh load");

		// The exact same gain is used for classical QoT and the Raman/GN power profile.
		LongitudinalClassicalQoT.Result qot=LongitudinalClassicalQoT.evaluate(
				saturated,F,H,.01,10,1,.04,true,3.16227766017,240,ALPHA);
		double expected=saturated.powerRatio(0,240,ALPHA);
		near(expected,qot.signalTransfer,1e-11,
				"classical signal transfer equals QKD/GN longitudinal power transfer");
		ok(qot.aseAtReceiverWHz>0 && Double.isFinite(qot.aseAtReceiverWHz),
				"finite positive ASE from chain");

		// With zero net gain, no ASE is generated by any unit gain stage.
		ClassicalPowerEvolution passive = new ClassicalPowerEvolution(80,0)
				.withBooster(1,0.04,false).withDynamicLoad(loads(false),240,ALPHA);
		LongitudinalClassicalQoT.Result p=LongitudinalClassicalQoT.evaluate(
				passive,F,H,.01,1,1,.04,false,3.16227766017,240,ALPHA);
		near(Math.exp(-ALPHA*240),p.signalTransfer,1e-11,"passive fibre limit");
		near(0,p.aseAtReceiverWHz,1e-12,"zero-gain amplifier ASE limit");

		// Original GN model is not altered: regression checks its separate class.
		System.out.println("PASS QKDBoosterIntegratedVerification");
	}
}
